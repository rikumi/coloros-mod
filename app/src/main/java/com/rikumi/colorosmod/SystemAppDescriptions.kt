    /** Restrictions take priority over recommendations, removal history and retention choices. */
    @StringRes
    fun recommendationRes(packageName: String, inactive: Boolean): Int = when {
        packageName in uninstallRestrictions -> R.string.system_app_recommendation_uninstallable
